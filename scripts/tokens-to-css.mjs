// Turns the hub's design-tokens.json into CSS custom properties.
//
// The JSON is PlayAlong's own format, specified in the hub's design-tokens.md:
// $type/$value with {dot.path} aliases. Not DTCG, deliberately, so this reader
// is written against that spec rather than against a standard.
//
//   node scripts/tokens-to-css.mjs
//
// Input  : external/playalong-hub/design-tokens.json  (a copy — see external/README.md)
// Output : src/tokens/tokens.css          (generated; do not hand-edit)
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = new URL('../external/playalong-hub/design-tokens.json', import.meta.url);
const OUT = new URL('../src/tokens/tokens.css', import.meta.url);
const doc = JSON.parse(readFileSync(SRC, 'utf8'));

const varName = (parts) =>
  '--' + parts.join('-').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

/** Walk a group, yielding [pathArray, token]. */
function* walk(node, path = []) {
  if (!node || typeof node !== 'object') return;
  if ('$value' in node) { yield [path, node]; return; }
  for (const [k, v] of Object.entries(node)) {
    if (!k.startsWith('$')) yield* walk(v, [...path, k]);
  }
}

/** Resolve "{a.b.c}" against the document; non-aliases pass through. */
function deref(value, seen = 0) {
  if (typeof value !== 'string' || !value.startsWith('{') || seen > 10) return value;
  let cur = doc;
  for (const seg of value.slice(1, -1).split('.')) {
    cur = cur?.[seg];
    if (cur === undefined) throw new Error(`alias ${value} does not resolve`);
  }
  return deref(cur.$value, seen + 1);
}

const px = (v) => (typeof v === 'string' ? v : `${v}px`);

// Figma names a weight; CSS wants a number. `font-weight: regular` is invalid
// and silently resolves to 400, which would quietly flatten Medium, SemiBold
// and ExtraBold to the same stroke.
const WEIGHT = {
  thin: 100, extralight: 200, light: 300, regular: 400, normal: 400,
  medium: 500, semibold: 600, bold: 700, extrabold: 800, black: 900,
};
const weight = (name) => {
  const key = String(name).toLowerCase().replace(/[^a-z]/g, '');
  const n = WEIGHT[key];
  if (!n) throw new Error(`unknown font weight "${name}" — add it to WEIGHT in this script`);
  return n;
};
const lines = [];
const section = (t) => lines.push('', `  /* ${t} */`);

section('Primitives — raw values. Prefer the semantic names below.');
for (const [path, tok] of walk(doc.primitives)) {
  if (tok.$type === 'color') lines.push(`  ${varName(path.slice(1))}: ${tok.$value};`);
}

section('Semantic — what a colour is for. These are the ones to use.');
for (const [path, tok] of walk(doc.semantic)) {
  lines.push(`  ${varName(path)}: ${deref(tok.$value)};`);
}

section('Gradients — styles in Figma; a colour variable cannot hold one.');
for (const [path, tok] of walk(doc.gradient)) {
  const v = tok.$value;
  const stops = v.stops.map((s) => `${s.color} ${Math.round(s.position * 100)}%`).join(', ');
  const fn = v.type === 'angular' ? 'conic-gradient' : 'linear-gradient';
  const head = v.type === 'angular' ? 'from 0deg' : '180deg';
  lines.push(`  ${varName(['gradient', ...path])}: ${fn}(${head}, ${stops});`);
}

section('Typography — one group of variables per style.');
for (const [path, tok] of walk(doc.typography)) {
  const v = tok.$value;
  const base = varName(['type', ...path]);
  lines.push(`  ${base}-family: "${deref(v.fontFamily)}";`);
  lines.push(`  ${base}-weight: ${weight(deref(v.fontWeight))};`);
  lines.push(`  ${base}-size: ${px(deref(v.fontSize))};`);
  lines.push(`  ${base}-line: ${px(deref(v.lineHeight))};`);
  const ls = v.letterSpacing;
  lines.push(`  ${base}-tracking: ${ls.unit === 'percent' ? `${ls.value / 100}em` : `${ls.value}px`};`);
  lines.push(`  ${base}-case: ${v.textCase === 'UPPER' ? 'uppercase' : 'none'};`);
}

const css = `/* GENERATED by scripts/tokens-to-css.mjs — do not hand-edit.
   Source: external/playalong-hub/design-tokens.json, a copy of a file in the
   private playalong-hub repository. Refresh both with: npm run external:sync
*/
:root {${lines.join('\n')}
}
`;
writeFileSync(OUT, css);
const count = [...walk(doc.primitives), ...walk(doc.semantic), ...walk(doc.gradient), ...walk(doc.typography)].length;
console.log(`tokens.css written — ${count} tokens in, ${css.split('\n').filter((l) => l.includes(': ')).length} CSS variables out`);
